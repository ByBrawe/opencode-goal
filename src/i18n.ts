export function resolveGoalLocale(raw?: string | null): GoalLocale {
  if (!raw) return "en"
  const normalized = raw.trim().replace(/\..*$/, "").replace(/@.*$/, "").replace(/_/g, "-").toLowerCase()
  if (!normalized) return "en"
  if (normalized === "pt-br" || normalized.startsWith("pt-br-")) return "pt-BR"
  if (["zh-tw", "zh-hk", "zh-mo", "zh-hant"].some((value) => normalized === value || normalized.startsWith(`${value}-`))) return "zh-TW"
  if (normalized === "zh-cn" || normalized === "zh-sg" || normalized === "zh-hans" || normalized.startsWith("zh-")) return "zh-CN"
  return BASE_LOCALE_ALIASES[normalized.split("-")[0] ?? ""] ?? "en"
}

export function currentGoalLocale(): GoalLocale {
  const configured = process.env.OPENCODE_GOAL_LANG
    ?? process.env.OPENCODE_GOAL_LANGUAGE
    ?? process.env.LC_ALL
    ?? process.env.LC_MESSAGES
    ?? process.env.LANG
  if (configured) return resolveGoalLocale(configured)
  try {
    return resolveGoalLocale(Intl.DateTimeFormat().resolvedOptions().locale)
  } catch {
    return "en"
  }
}

