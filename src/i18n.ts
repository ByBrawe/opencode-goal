function normalizeIntent(text: string): string {
  return text
    .trim()
    .toLocaleLowerCase()
    .replace(/[.!?。！？…]+$/gu, "")
    .replace(/\s+/gu, " ")
}

const ALL_RESUME_INTENTS = new Set(
  Object.values(RESUME_INTENTS).flatMap((values) => values.map(normalizeIntent)),
)

export function isNaturalResumeText(text: string): boolean {
  return ALL_RESUME_INTENTS.has(normalizeIntent(text))
}

export function translateCoreText(text: string, locale: GoalLocale = currentGoalLocale()): string {
  if (locale === "en") return text
  const labels = LABELS[locale]
  let translated = text

  translated = translated.replace(/No active goal\./g, labels.noActiveGoal)
  translated = translated.replace(/^Goal Contract$/gm, labels.goalContract)
  translated = translated.replace(/^Current Goal:/gm, `${labels.currentGoal}:`)
  translated = translated.replace(/^Goal:/gm, `${labels.goal}:`)
  translated = translated.replace(/^Objective:/gm, `${labels.objective}:`)
  translated = translated.replace(/^Status:/gm, `${labels.status}:`)
  translated = translated.replace(/^Revision:/gm, `${labels.revision}:`)
  translated = translated.replace(/^Budget:/gm, `${labels.budget}:`)
  translated = translated.replace(/^Stop reason:/gm, `${labels.stopReason}:`)
  translated = translated.replace(/^Requirements:/gm, `${labels.requirements}:`)
  translated = translated.replace(/^Success criteria:/gm, `${labels.successCriteria}:`)
  translated = translated.replace(/^Constraints \/ non-goals:/gm, `${labels.constraintsNonGoals}:`)
  translated = translated.replace(/^Host verification contracts:/gm, `${labels.hostVerificationContracts}:`)
  translated = translated.replace(/No live Goal/g, labels.noLiveGoal)
  translated = translated.replace(/Goal storage unavailable/g, labels.goalStorageUnavailable)
  translated = translated.replace(/Queue storage unavailable/g, labels.queueStorageUnavailable)
  translated = translated.replace(/^Queue ·/gm, `${labels.queue} ·`)
  translated = translated.replace(/(\d+\/\d+) proven\b/g, `$1 ${labels.proven}`)
  translated = translated.replace(/^turns /gm, `${labels.turns} `)
  translated = translated.replace(/ · tokens /g, ` · ${labels.tokens} `)
  translated = translated.replace(/(\+\d+) more\b/g, `$1 ${labels.more}`)
  translated = translated.replace(/^Goal paused\./gm, labels.goalPaused)

  return translated
}
